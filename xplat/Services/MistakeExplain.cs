namespace Matsubakira.Services;

/// <summary>
/// «Почему неверно»: ты выбрал X, а нужно Y — коротко, чем они отличаются.
/// Частицы и частые служебные формы описаны по смыслу; для остального — общий совет.
/// </summary>
public static class MistakeExplain
{
    static readonly Dictionary<string, string> Role = new()
    {
        ["は"] = "тема фразы: «что касается…» (и противопоставление)",
        ["が"] = "подлежащее, на которое падает акцент («именно он»); а ещё с ある/いる, 好き, 上手, 分かる, できる, 欲しい",
        ["を"] = "прямой объект действия (что едим, что читаем); место, по которому движемся (道を歩く)",
        ["に"] = "точка: время (7時に), где что-то находится (ある/いる), куда идём, кому даём",
        ["で"] = "место, где происходит действие (図書館で読む); способ и средство (バスで, 日本語で); причина",
        ["へ"] = "направление движения «в сторону…» (почти как に с глаголами движения)",
        ["と"] = "«и» в полном перечне, «вместе с кем», цитата (〜と思う・〜と言う)",
        ["や"] = "«и… и другие» — неполный перечень",
        ["も"] = "«тоже», «и… и…»; с числом — «целых»",
        ["の"] = "связь двух существительных: принадлежность, «какой» (日本の車)",
        ["から"] = "«от / с» (начало во времени или пространстве) или «потому что»",
        ["まで"] = "«до» — конечная точка; までに — «к сроку, не позже»",
        ["までに"] = "«к сроку, не позже»",
        ["か"] = "вопрос в конце фразы или «или» между словами",
        ["より"] = "«чем» при сравнении (AはBより大きい)",
        ["ので"] = "«так как» — мягкая, объективная причина",
        ["のに"] = "«хотя / а ведь» — результат вопреки ожиданию",
        ["ながら"] = "«делая одно, делаю другое» — одновременные действия одного человека",
        ["けど"] = "«но» (разговорное)",
        ["でも"] = "«но, однако» в начале фразы; «даже / хоть» после слова",
        ["ば"] = "условие «если…», часто общее правило",
        ["たら"] = "«если / когда… (после того как)» — одно конкретное событие",
        ["なら"] = "«если уж речь о…» — совет по теме собеседника",
        ["ように"] = "цель, которую не контролируешь («чтобы смочь…»); 〜ようになる — «стал (уметь)»",
        ["ために"] = "цель, зависящая от тебя («ради, чтобы»)",
        ["ところ"] = "момент действия: 〜るところ «вот-вот», 〜ているところ «как раз сейчас», 〜たところ «только что»",
        ["ばかり"] = "«только и делает», 〜たばかり — «только что (по ощущению)»",
        ["こと"] = "превращает действие в существительное (〜ことができる, 〜ことにする)",
        ["もの"] = "конкретная вещь; 〜ものだ — «так уж устроено / раньше часто…»",
        ["わけ"] = "вывод «вот почему / значит»; 〜わけではない — «не то чтобы»",
        ["そう"] = "«выглядит как…» (основа + そう) или «говорят, что…» (простая форма + そうだ)",
        ["よう"] = "«похоже, что…» (по своим наблюдениям)",
        ["らしい"] = "«говорят / похоже» — по чужим сведениям",
        ["みたい"] = "разговорное «похоже, как будто»",
    };

    /// <summary>Объяснение ошибки или null, если сказать нечего (не наш случай).</summary>
    public static string? For(string answer, string chosen)
    {
        if (string.IsNullOrEmpty(chosen) || chosen == answer) return null;
        var right = answer.Split('|')[0];
        bool a = Role.TryGetValue(right, out var ra), c = Role.TryGetValue(chosen, out var rc);
        if (a && c) return $"Ты выбрал «{chosen}» — это {rc}.\nА здесь нужна «{right}»: {ra}.";
        if (a) return $"Здесь нужна «{right}»: {ra}.";
        // формы глагола: чем отличается выбранное окончание
        if (right.Length > 0 && chosen.Length > 0 && (right.StartsWith(chosen) || chosen.StartsWith(right)))
            return $"Почти: «{chosen}» — неполная или лишняя форма. Нужно «{right}» целиком.";
        if (right.EndsWith("ません") || right.EndsWith("なかった") || right.EndsWith("ない"))
            return $"Здесь отрицание — «{right}». Посмотри, есть ли в переводе «не».";
        if (right.EndsWith("ました") || right.EndsWith("た") && !right.EndsWith("たい"))
            return $"Здесь прошедшее время — «{right}». Ищи в фразе слова вроде きのう, 先週.";
        return null;
    }
}
