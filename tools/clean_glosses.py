def clean(g):
    s = g
    s = re.sub(r"\s*,?\s*\b[AK]\s+[AК]\.[^;]*", "", s)                     # «K К. сейчас вышел…», «A чек на имя господина А»
    s = re.sub(r"\(\((чаще|редко)\),?\s*\)", "", s)                         # ((чаще), )
    s = re.sub(r"\((неперех|перех|связ|в сочет[^)]*|тж\. постпозиц|в знач\.[^)]*|как сказ|как опред|в конце предложения|перед гл|с отриц)\.?:?\)\s*;?", lambda m: "(с отриц.) " if m.group(1) == "с отриц" else "", s)
    s = re.sub(r"(^|[\s,;])[абвг]\)\s*", r"\1", s)                          # а) б)
    s = s.replace("～", "").replace("◇", "")
    s = re.sub(r"(^|;)\s*:\s*", r"\1 ", s)                                   # «; : раньше»
    s = re.sub(r",\s*:\s*", ", ", s)
    s = re.sub(r"(,\s*\d+)+\s*$", "", s)                                     # хвост «, 2» и «1, 3, 5»
    s = re.sub(r"\(\s*\)", "", s)
    s = re.sub(r"\s*([,;])\s*(?=[,;])", "", s)                               # «, ;»
    s = re.sub(r"\s{2,}", " ", s)
    s = s.strip(" ,;:")
    # повторы одного и того же значения через запятую/точку с запятой
    parts, seen = [], set()
    for p in re.split(r"\s*;\s*", s):
        sub = []
        for q in re.split(r"\s*,\s+", p):
            k = q.strip().lower()
            if k and k not in seen: seen.add(k); sub.append(q.strip())
        if sub: parts.append(", ".join(sub))
    s = "; ".join(parts)
    if s.count("(") > s.count(")"): s += ")"   # «(от должности» — обрезанная скобка
    return s

